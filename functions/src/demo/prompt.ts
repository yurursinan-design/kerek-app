import { addDays, dayHours, localNow, toHHMM } from './calendar';
import { money, weekdayName } from './texts';
import type { Business } from './types';

const SHORT_DAYS = ['пн', 'вт', 'ср', 'чт', 'пт', 'сб', 'вс'];

function hoursText(b: Business): string {
  return b.hours
    .map((h, i) => `${SHORT_DAYS[i]} ${h ? `${h[0]}–${h[1]}` : 'выходной'}`)
    .join(', ');
}

/** Next two weeks with weekdays, so "в субботу" or "через неделю" never needs date arithmetic */
function calendarText(b: Business, nowMs: number): string {
  const now = localNow(nowMs);
  const lines: string[] = [];
  for (let d = 0; d < 14; d++) {
    const date = addDays(now.date, d);
    const label = d === 0 ? ' (сегодня)' : d === 1 ? ' (завтра)' : '';
    const h = dayHours(b, date);
    lines.push(`${weekdayName(date, 'ru')} ${date}${label}${h ? '' : ' — выходной'}`);
  }
  return lines.join('\n');
}

function catalogText(b: Business): string {
  if (b.kind === 'order') {
    return b.products
      .map((p) => {
        const price = `${p.priceFrom ? 'от ' : ''}${money(p.price)}${p.unit === 'кг' ? ' за кг' : p.unit === 'шт' ? ' за шт' : ' за набор'}`;
        const ready = p.available ? 'есть сегодня в витрине' : `под заказ, готовим ${p.leadDays} дн.`;
        return `- ${p.id}: ${p.ru} / ${p.kz} — ${price}; ${ready}${p.note ? `. ${p.note}` : ''}`;
      })
      .join('\n');
  }
  return b.services
    .map((s) => {
      const who = s.staff.map((id) => b.staff.find((x) => x.id === id)?.name).filter(Boolean).join(', ');
      return `- ${s.id}: ${s.ru} / ${s.kz} — ${s.priceFrom ? 'от ' : ''}${money(s.price)}, ${s.minutes} мин; делает: ${who}${s.note ? `. ${s.note}` : ''}`;
    })
    .join('\n');
}

